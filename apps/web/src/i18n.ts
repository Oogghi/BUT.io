export type Language = 'en' | 'fr';

function readLanguage(): Language {
  try {
    const saved = localStorage.getItem('but.language');
    if (saved === 'en' || saved === 'fr') return saved;
  } catch {
    // Browser storage can be unavailable; use the browser language instead.
  }
  return ((navigator.languages ?? [navigator.language])
    .map((tag) => tag.slice(0, 2).toLowerCase())
    .find((code) => code === 'en' || code === 'fr') ?? 'en') as Language;
}

export const lang = readLanguage();

document.documentElement.lang = lang;

export const t = lang === 'fr' ? fr : en;

export function setLanguage(next: Language) {
  try {
    localStorage.setItem('but.language', next);
  } catch {
    // The next page load will fall back to the browser language.
  }
  window.location.reload();
}

export function wordError(code: string): string {
  return Object.hasOwn(t.bp.wordErrors, code)
    ? t.bp.wordErrors[code as WordError]
    : t.actionFailed;
}

export function planError(code: string): string {
  return Object.hasOwn(t.ta.planErrors, code)
    ? t.ta.planErrors[code as PlanError]
    : t.actionFailed;
}

export function blackjackError(code: string): string {
  return Object.hasOwn(t.bj.actionErrors, code)
    ? t.bj.actionErrors[code as BlackjackActionError]
    : t.actionFailed;
}

/** Localize a lobby error code from the server; anything else (e.g. a transport error) gets `fallback`. */
export function lobbyError(code: string, fallback = t.actionFailed) {
  return Object.hasOwn(t.lobbyErrors, code)
    ? t.lobbyErrors[code as LobbyErrorCode]
    : fallback;
}
